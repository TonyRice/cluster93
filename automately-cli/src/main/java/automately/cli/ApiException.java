package automately.cli;

/** An error answer from the API: its status, the envelope's code, and its message. */
public final class ApiException extends CliException {

    private final int status;
    private final String code;

    public ApiException(int status, String code, String message) {
        super(message);
        this.status = status;
        this.code = code;
    }

    public int status() {
        return status;
    }

    public String code() {
        return code;
    }
}
