// Vendors Node's own streams into the isolate (D-095, D-100): readable-stream (Node's stream code, packaged for outside
// Node) and string_decoder, bundled into ES modules on the isolate's stand-ins for buffer, events and process.
// Run from this folder: npm ci --ignore-scripts && node build.mjs. npm ci checks every package against the lockfile's
// integrity hash; the output is committed, so building Automately never needs Node.
import * as esbuild from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = new URL('../../automately-runtime-javet/src/main/resources/automately/runtime/javet/js/node/', import.meta.url).pathname;
const lock = JSON.parse(readFileSync(new URL('./package-lock.json', import.meta.url), 'utf8'));
const pinned = Object.entries(lock.packages).filter(([path]) => path.startsWith('node_modules/') && !lock.packages[path].dev)
  .map(([path, info]) => `//   ${path.slice('node_modules/'.length)}@${info.version} ${info.integrity}`).join('\n');

// A require() of one of Node's modules becomes a static import whose default export is module.exports (as in D-093).
const ESM = 'automately-esm:';
const builtins = { name: 'builtins', setup(b) {
  b.onResolve({ filter: /^automately-esm:/ }, (a) => ({ path: a.path.slice(ESM.length), namespace: 'esm' }));
  b.onResolve({ filter: /^(node:)?(buffer|events|process|string_decoder)\/?$/ }, (a) => {
    const name = 'node:' + a.path.replace(/\/$/, '').replace(/^node:/, '');
    return a.kind === 'require-call' ? { path: name, namespace: 'required' } : { path: name, external: true };
  });
  // The isolate has no window or self, which abort-controller's browser build reads: use its real implementation.
  b.onResolve({ filter: /^abort-controller$/ }, () => ({ path: new URL('./node_modules/abort-controller/dist/abort-controller.js', import.meta.url).pathname }));
  b.onLoad({ filter: /.*/, namespace: 'required' }, (a) => ({ contents: 'module.exports = require(' + JSON.stringify(ESM + a.path) + ').default;', loader: 'js' }));
  b.onLoad({ filter: /.*/, namespace: 'esm' }, (a) => ({ contents: 'export { default } from ' + JSON.stringify(a.path) + ';', loader: 'js' }));
} };

async function bundle(entry) {
  const result = await esbuild.build({ entryPoints: [entry], bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2022',
    plugins: [builtins], mainFields: ['browser', 'main'], logLevel: 'warning', legalComments: 'inline' });
  // `export default require_x();` becomes a named module object, so Node's named exports can come from it.
  return result.outputFiles[0].text.replace(/export default (require_[A-Za-z0-9_]+\(\));\s*$/, 'const exported = $1;\n');
}

const header = (what) => `// ${what}: generated by scripts/vendor-stream (D-100), with these npm packages installed, each checked by npm ci against
// its hash (buffer, events and process are replaced by the isolate's own stand-ins rather than bundled):
${pinned}
// MIT licensed; the licences are in THIRD-PARTY-LICENSES.txt beside this file. Don't edit by hand: change and rerun the script.
`;

const STREAM_NAMES = ['Readable', 'Writable', 'Duplex', 'Transform', 'PassThrough', 'Stream', 'pipeline', 'finished', 'promises', 'addAbortSignal',
  'compose', 'destroy', 'isDisturbed', 'isErrored', 'isReadable', 'getDefaultHighWaterMark', 'setDefaultHighWaterMark', 'duplexPair'];
writeFileSync(OUT + 'stream.js', header("Node's stream") + await bundle('stream-entry.cjs')
  + 'export default exported;\nexport const { ' + STREAM_NAMES.join(', ') + ' } = exported;\n');
writeFileSync(OUT + 'string_decoder.js', header("Node's string_decoder") + await bundle('string_decoder-entry.cjs')
  + 'export default exported;\nexport const { StringDecoder } = exported;\n');
writeFileSync(OUT + 'stream_promises.js', "// Node's stream/promises, from the vendored stream (D-100).\nimport stream from 'node:stream';\n"
  + 'const promises = stream.promises;\nexport default promises;\nexport const { pipeline, finished } = promises;\n');

const licences = ['readable-stream', 'string_decoder', 'safe-buffer', 'abort-controller', 'event-target-shim'].map((name) => {
  const dir = new URL('./node_modules/' + name + '/', import.meta.url).pathname;
  const file = ['LICENSE', 'LICENSE.md', 'license'].map((f) => dir + f).find((f) => { try { readFileSync(f); return true; } catch { return false; } });
  return '=== ' + name + ' ===\n' + readFileSync(file, 'utf8').trim() + '\n';
});
writeFileSync(OUT + 'THIRD-PARTY-LICENSES.txt', 'Vendored into js/node/stream.js and js/node/string_decoder.js (D-100).\n\n' + licences.join('\n'));
console.log('Wrote stream.js, stream_promises.js, string_decoder.js and THIRD-PARTY-LICENSES.txt to', OUT);
